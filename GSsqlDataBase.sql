-- CONSULTA 01: Quais servicos de acolhimento estao disponiveis na Zona Sul?
SELECT
    NOME,
    REGIAO,
    BAIRRO,
    ENDERECO,
    TELEFONE
FROM GS_SERVICO_ACOLHIMENTO
WHERE UPPER(REGIAO) = 'ZONA SUL'
ORDER BY NOME ASC;

-- CONSULTA 02: Quais servicos existem e a quais categorias pertencem?
SELECT
    S.NOME AS UNIDADE,
    C.NOME AS CATEGORIA,
    S.REGIAO,
    S.ENDERECO
FROM GS_SERVICO_ACOLHIMENTO S
INNER JOIN GS_CATEGORIA_SERVICO C
    ON S.ID_CATEGORIA_SERVICO = C.ID_CATEGORIA_SERVICO
ORDER BY C.NOME, S.NOME;

-- CONSULTA 03: Quais conteudos ativos estao associados a cada categoria?
SELECT
    C.TITULO,
    C.ASSUNTO,
    CAT.NOME AS CATEGORIA,
    C.FONTE_INFORMACAO
FROM GS_CONTEUDO C
INNER JOIN GS_CONTEUDO_CATEGORIA CC
    ON C.ID_CONTEUDO = CC.ID_CONTEUDO
INNER JOIN GS_CATEGORIA_CONTEUDO CAT
    ON CC.ID_CATEGORIA_CONTEUDO = CAT.ID_CATEGORIA_CONTEUDO
WHERE C.STATUS = 'ATIVO'
ORDER BY C.TITULO;

-- CONSULTA 04: Quantos registros de bem-estar cada usuario possui?
SELECT
    U.ID_USUARIO,
    U.NOME,
    COUNT(R.ID_REGISTRO) AS TOTAL_REGISTROS
FROM GS_USUARIO U
LEFT JOIN GS_REGISTRO_BEM_ESTAR R
    ON U.ID_USUARIO = R.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY TOTAL_REGISTROS DESC;

-- CONSULTA 05: Quais regioes possuem pelo menos duas unidades de acolhimento?
SELECT
    REGIAO,
    COUNT(ID_SERVICO) AS TOTAL_UNIDADES
FROM GS_SERVICO_ACOLHIMENTO
GROUP BY REGIAO
HAVING COUNT(ID_SERVICO) >= 2
ORDER BY TOTAL_UNIDADES DESC;

-- CONSULTA 06: Quais sao as estatisticas dos niveis de humor registrados por usuario?
SELECT
    U.NOME,
    COUNT(R.ID_REGISTRO) AS TOTAL_REGISTROS,
    SUM(R.NIVEL_HUMOR) AS SOMA_NIVEIS_HUMOR,
    ROUND(AVG(R.NIVEL_HUMOR), 2) AS MEDIA_HUMOR,
    MAX(R.NIVEL_HUMOR) AS MAIOR_NIVEL_HUMOR,
    MIN(R.NIVEL_HUMOR) AS MENOR_NIVEL_HUMOR
FROM GS_USUARIO U
INNER JOIN GS_REGISTRO_BEM_ESTAR R
    ON U.ID_USUARIO = R.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY MEDIA_HUMOR DESC;

-- CONSULTA 07: Quais unidades pertencem a categoria CAPS?
SELECT
    NOME,
    REGIAO,
    ENDERECO,
    TELEFONE
FROM GS_SERVICO_ACOLHIMENTO
WHERE ID_CATEGORIA_SERVICO IN (
    SELECT ID_CATEGORIA_SERVICO
    FROM GS_CATEGORIA_SERVICO
    WHERE UPPER(NOME) LIKE '%CAPS%'
)
ORDER BY REGIAO, NOME;

-- CONSULTA 08: Quais conteudos ativos abordam o tema ansiedade?
SELECT
    ID_CONTEUDO,
    TITULO,
    ASSUNTO,
    DESCRICAO,
    FONTE_INFORMACAO,
    DATA_PUBLICACAO
FROM GS_CONTEUDO
WHERE (
    UPPER(ASSUNTO) LIKE '%ANSIEDADE%'
    OR UPPER(TITULO) LIKE '%ANSIEDADE%'
)
AND STATUS = 'ATIVO'
ORDER BY DATA_PUBLICACAO DESC;

-- CONSULTA 09: Quais categorias possuem conteudos associados, incluindo categorias sem conteudo?
SELECT
    CAT.NOME AS CATEGORIA,
    C.TITULO AS CONTEUDO
FROM GS_CONTEUDO_CATEGORIA CC
RIGHT JOIN GS_CATEGORIA_CONTEUDO CAT
    ON CC.ID_CATEGORIA_CONTEUDO = CAT.ID_CATEGORIA_CONTEUDO
LEFT JOIN GS_CONTEUDO C
    ON CC.ID_CONTEUDO = C.ID_CONTEUDO
ORDER BY CAT.NOME;

-- CONSULTA 10: Qual o historico de humor dos usuarios e ha quantos dias cada registro foi feito?
SELECT
    U.NOME,
    R.DATA_REGISTRO,
    R.HUMOR,
    R.NIVEL_HUMOR,
    TRUNC(SYSDATE) - TRUNC(R.DATA_REGISTRO)
        AS DIAS_DESDE_REGISTRO
FROM GS_USUARIO U
INNER JOIN GS_REGISTRO_BEM_ESTAR R
    ON U.ID_USUARIO = R.ID_USUARIO
WHERE R.DATA_REGISTRO IS NOT NULL
ORDER BY R.DATA_REGISTRO DESC;