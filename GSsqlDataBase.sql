CREATE TABLE GS_USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_GS_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_GS_USUARIO_EMAIL UNIQUE (EMAIL) );

CREATE TABLE GS_CATEGORIA_SERVICO (
    ID_CATEGORIA_SERVICO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(80) NOT NULL,
    DESCRICAO VARCHAR2(300),
    CONSTRAINT PK_GS_CAT_SERVICO PRIMARY KEY (ID_CATEGORIA_SERVICO),
    CONSTRAINT UK_GS_CAT_SERVICO_NOME UNIQUE (NOME));

CREATE TABLE GS_SERVICO_ACOLHIMENTO (
    ID_SERVICO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CATEGORIA_SERVICO NUMBER NOT NULL,
    NOME VARCHAR2(150) NOT NULL,
    ENDERECO VARCHAR2(200) NOT NULL,
    BAIRRO VARCHAR2(100),
    REGIAO VARCHAR2(100) NOT NULL,
    TELEFONE VARCHAR2(20),
    HORARIO_FUNCIONAMENTO VARCHAR2(150),
    DESCRICAO_SERVICOS VARCHAR2(500),
    FONTE_INFORMACAO VARCHAR2(300) NOT NULL,
    DATA_VERIFICACAO DATE,
    CONSTRAINT PK_GS_SERVICO PRIMARY KEY (ID_SERVICO),
    CONSTRAINT FK_GS_SERVICO_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA_SERVICO)
        REFERENCES GS_CATEGORIA_SERVICO (ID_CATEGORIA_SERVICO));

CREATE TABLE GS_CATEGORIA_CONTEUDO (
    ID_CATEGORIA_CONTEUDO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(300),
    CONSTRAINT PK_GS_CAT_CONTEUDO PRIMARY KEY (ID_CATEGORIA_CONTEUDO),
    CONSTRAINT UK_GS_CAT_CONTEUDO_NOME UNIQUE (NOME));

CREATE TABLE GS_CONTEUDO (
    ID_CONTEUDO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR2(200) NOT NULL,
    ASSUNTO VARCHAR2(150) NOT NULL,
    DESCRICAO VARCHAR2(500),
    MATERIAL CLOB NOT NULL,
    FONTE_INFORMACAO VARCHAR2(300) NOT NULL,
    DATA_PUBLICACAO DATE DEFAULT SYSDATE,
    STATUS VARCHAR2(15) DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT PK_GS_CONTEUDO PRIMARY KEY (ID_CONTEUDO),
    CONSTRAINT CK_GS_CONTEUDO_STATUS
        CHECK (STATUS IN ('ATIVO', 'INATIVO')));

CREATE TABLE GS_CONTEUDO_CATEGORIA (
    ID_CONTEUDO NUMBER NOT NULL,
    ID_CATEGORIA_CONTEUDO NUMBER NOT NULL,
    CONSTRAINT PK_GS_CONTEUDO_CATEGORIA
        PRIMARY KEY (ID_CONTEUDO, ID_CATEGORIA_CONTEUDO),
    CONSTRAINT FK_GS_CC_CONTEUDO
        FOREIGN KEY (ID_CONTEUDO)
        REFERENCES GS_CONTEUDO (ID_CONTEUDO),
    CONSTRAINT FK_GS_CC_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA_CONTEUDO)
        REFERENCES GS_CATEGORIA_CONTEUDO (ID_CATEGORIA_CONTEUDO));

CREATE TABLE GS_REGISTRO_BEM_ESTAR (
    ID_REGISTRO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    DATA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
    HUMOR VARCHAR2(50) NOT NULL,
    NIVEL_HUMOR NUMBER(1) NOT NULL,
    SENTIMENTOS VARCHAR2(200),
    OBSERVACOES VARCHAR2(1000),
    CONSTRAINT PK_GS_REGISTRO PRIMARY KEY (ID_REGISTRO),
    CONSTRAINT FK_GS_REGISTRO_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES GS_USUARIO (ID_USUARIO),
    CONSTRAINT CK_GS_NIVEL_HUMOR
        CHECK (NIVEL_HUMOR BETWEEN 1 AND 5));

CREATE TABLE GS_ADMINISTRADOR (
    ID_ADMINISTRADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    NIVEL_ACESSO VARCHAR2(20) DEFAULT 'ADMIN' NOT NULL,
    CONSTRAINT PK_GS_ADMINISTRADOR PRIMARY KEY (ID_ADMINISTRADOR),
    CONSTRAINT UK_GS_ADMIN_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT FK_GS_ADMIN_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES GS_USUARIO (ID_USUARIO),
    CONSTRAINT CK_GS_ADMIN_ACESSO
        CHECK (NIVEL_ACESSO IN ('ADMIN', 'SUPERVISOR')));


CREATE TABLE GS_FAVORITO (
    ID_USUARIO NUMBER NOT NULL,
    ID_CONTEUDO NUMBER NOT NULL,
    DATA_FAVORITO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_GS_FAVORITO
        PRIMARY KEY (ID_USUARIO, ID_CONTEUDO),
    CONSTRAINT FK_GS_FAVORITO_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES GS_USUARIO (ID_USUARIO),
    CONSTRAINT FK_GS_FAVORITO_CONTEUDO
        FOREIGN KEY (ID_CONTEUDO)
        REFERENCES GS_CONTEUDO (ID_CONTEUDO));

